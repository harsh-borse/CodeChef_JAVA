import java.util.*;
class Codechef {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int C;
        C = scanner.nextInt();
        if (C > 20) {
            System.out.println("HOT");
        } else {
            System.out.println("COLD");
        }
        scanner.close();
    }
}
